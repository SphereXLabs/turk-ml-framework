export function lookupArticle(query) {
  const q = String(query || "").toLocaleLowerCase("tr-TR")
    .normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  if (!q.trim()) return null;
  for (const [alias, key] of Object.entries(ARTICLE_ALIASES)) {
    const a = alias.toLocaleLowerCase("tr-TR").normalize("NFD").replace(/[\u0300-\u036f]/g, "");
    if (q.includes(a) && ARTICLES[key]) return { key, ...ARTICLES[key] };
  }
  // longest key first for multiword-ish slugs
  const keys = Object.keys(ARTICLES).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    const compact = key.replace(/_/g, " ");
    if (q.includes(key) || q.includes(compact)) return { key, ...ARTICLES[key] };
    const title = ARTICLES[key].title.toLocaleLowerCase("tr-TR")
      .normalize("NFD").replace(/[\u0300-\u036f]/g, "");
    if (title && q.includes(title)) return { key, ...ARTICLES[key] };
  }
  return null;
}

export function datasetStats() {
  const per = {};
  let total = 0;
  for (const i of INTENTS) {
    per[i] = (DATASET[i] || []).length;
    total += per[i];
  }
  return { total, intents: INTENTS.length, articles: Object.keys(ARTICLES).length, per };
}
